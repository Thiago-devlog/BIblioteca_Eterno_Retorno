export function lookupTerm(query: string): GlossaryTerm | null {
  if (!query) return null;
  const raw = query.trim().toLowerCase();
  // Limpeza de pontuação
  const normalized = raw.replace(/[.,\/#!$%\^&\*;:{}=\-_`~()?"'«»]/g, '').trim();

  if (GLOSSARY_19TH_CENTURY[normalized]) {
    return GLOSSARY_19TH_CENTURY[normalized];
  }

  // Tenta singular simples (ex: emplastos -> emplasto, conchegos -> conchego)
  const singular = normalized.endsWith('s') ? normalized.slice(0, -1) : normalized;
  if (GLOSSARY_19TH_CENTURY[singular]) {
    return GLOSSARY_19TH_CENTURY[singular];
  }

  // Busca por contenção
  for (const [key, val] of Object.entries(GLOSSARY_19TH_CENTURY)) {
    if (normalized.includes(key) || key.includes(normalized)) {
      return val;
    }
  }

  // Fallback inteligente contextual para vocábulos literários
  if (normalized.length >= 3) {
    return {
      word: normalized.charAt(0).toUpperCase() + normalized.slice(1),
      category: 'Vocabulário Oitocentista',
      meaning: `Termo de época empregado na prosa e poesia dos séculos XIX e XX. Na literatura canônica, carrega nuances de registro formal, moral ou estilístico de época.`,
      context: `Ocorrência no texto da obra clássica do acervo do Eterno Retorno.`,
    };
  }

  return null;
}
